"""Plan 23 amendment 1, Step 0: the Ch. 4 design decisions as worded at 94c049d.

Extracts D1-D9 and the design-rationale table verbatim from
`git show 94c049d:thesis/implementation_chapter.tex`, splits each decision into
paragraphs, and gives every paragraph an id (D4.p3) with its line range at that
commit. The design register cites these ids. Nothing is paraphrased: each
paragraph is the LaTeX source as committed.

Usage: .venv/bin/python thesis/notes/thesis_completion/artifacts/23-am1-design-text.py
Writes 23-am1-design-text-94c049d.md next to this script.
"""

import hashlib
import pathlib
import re
import subprocess

COMMIT = "94c049d"
PATH = "thesis/implementation_chapter.tex"
OUT = pathlib.Path(__file__).with_name("23-am1-design-text-94c049d.md")


def main():
    full = subprocess.run(["git", "rev-parse", COMMIT], capture_output=True, text=True, check=True).stdout.strip()
    blob = subprocess.run(["git", "show", f"{COMMIT}:{PATH}"], capture_output=True, text=True, check=True).stdout
    lines = blob.split("\n")
    heads = [(i, m.group(1)) for i, l in enumerate(lines) if (m := re.match(r"\\subsection\{(D\d+): ", l))]
    t0 = next(i for i, l in enumerate(lines) if "label{tab:design-rationale}" in l)
    b = max(i for i in range(t0) if lines[i].strip() == "\\begingroup")
    e = next(i for i in range(t0, len(lines)) if lines[i].strip() == "\\endgroup")
    # The rationale table sits inside D9's subsection; it gets its own entry, not D9's.
    ends = sorted([i for i, l in enumerate(lines) if re.match(r"\\(sub)?section\{", l)] + [b])
    out = [
        "# Ch. 4 design decisions as worded at 94c049d (plan 23 amendment 1, Step 0)",
        "",
        f"Source: `git show {COMMIT}:{PATH}` (commit {full}, 9 September 2026, before the cycle-1 runs).",
        f"Blob SHA-256: {hashlib.sha256(blob.encode()).hexdigest()}.",
        "Generated by `23-am1-design-text.py`. Each paragraph is the committed LaTeX source, unedited.",
        "Paragraph ids (D4.p3) are what the design register cites. Line numbers are 1-based, at that commit.",
        "",
    ]
    for d, (start, name) in enumerate(heads):
        stop = min(e for e in ends if e > start)
        out += [f"## {name}", "", f"Lines {start + 1}-{stop}.", ""]
        para, first, n = [], None, 0
        for i in range(start, stop + 1):
            l = lines[i] if i < stop else ""
            if l.strip():
                if first is None:
                    first = i
                para.append(l)
            elif para:
                n += 1
                out += [f"**{name}.p{n}** (lines {first + 1}-{i})", "", "```latex", *para, "```", ""]
                para, first = [], None
    out +=["## Design-rationale table", "", f"**T.rationale** (lines {b + 1}-{e + 1})", "", "```latex", *lines[b : e + 1], "```", ""]
    OUT.write_text("\n".join(out))
    print(OUT, hashlib.sha256(OUT.read_bytes()).hexdigest())


if __name__ == "__main__":
    main()
